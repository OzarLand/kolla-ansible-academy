#!/usr/bin/env python3
"""Summarise every lab run into a Markdown results table (annex/lab/results.md)."""
import collections, json, os, sys
ROOT = os.environ.get('KOLLA_LAB_ROOT', os.path.expanduser('~/kolla-lab')) + '/lab/runs/'
OUT = sys.argv[1]
DESC = {
 't0-deploy': 'Fresh `deploy` (3 ctl, 2 net, 3 cmp, 1 storage, 1 mon)',
 't1-redeploy': '`deploy` again, nothing changed (idempotency)',
 's01-reconf-nova-nochange': '`-t nova reconfigure`, nothing changed',
 's02-reconf-nova-globalconf': '`-t nova reconfigure` after `/etc/kolla/config/nova.conf` change',
 's03-reconf-nova-computeconf': '`-t nova reconfigure` after `/etc/kolla/config/nova/nova-compute.conf` change',
 's04-reconf-nova-schedconf': '`-t nova reconfigure` after `/etc/kolla/config/nova/nova-scheduler.conf` change',
 's05-reconf-neutron-ml2': '`-t neutron reconfigure` after `/etc/kolla/config/neutron/ml2_conf.ini` change',
 's06-reconf-neutron-global': '`-t neutron reconfigure` after `/etc/kolla/config/neutron.conf` change',
 's07-reconf-nova-enable-barbican': '`enable_barbican: yes` + `-t nova reconfigure` (barbican itself not deployed)',
 's08-reconf-common-enable-barbican': '`enable_barbican: yes` + `-t common reconfigure`',
 's09a-deploy-nova-newdigest-nopull': 'nova-compute image rebuilt under same tag, `-t nova deploy` without pull',
 's09b-pull-nova-newdigest': 'same, `-t nova pull`',
 's09c-deploy-nova-after-pull': 'same, `-t nova deploy` after the pull',
 's10-pull-all-newtag': '`openstack_tag` changed, `pull`',
 's11-deploy-all-newtag': '`openstack_tag` changed, `deploy` (after pull)',
 's12-add-controller-reconf-nova-neutron': 'control04 added to inventory (rabbitmq/memcached member), `-t nova,neutron reconfigure`',
 's13-limit-compute-reconf-nova': 'nova-compute override, `-t nova reconfigure --limit compute001`',
 's14-genconfig-nova': 'nova.conf override, `-t nova genconfig`',
 's15-deploycontainers-compute001': 'after s14: `-t nova deploy-containers --limit compute001`',
 's16-reconf-nova-serial1': 'nova.conf override, `-t nova reconfigure` with `kolla_serial=1`',
 's17-add-compute004-limit': 'compute004 added, `deploy --limit compute004`',
 's18-reconfigure-all-nochange': '`reconfigure`, no tag, nothing changed',
 's19-reconf-haproxy-nochange': '`-t haproxy reconfigure`, nothing changed',
 'sc-deploy-10': 'Scale: fresh `deploy`, 10 computes (forks 20)',
 'sc-reconf-nova-10': 'Scale: `-t nova reconfigure`, no change, 10 computes (forks 20)',
 'sc-deploy-30': 'Scale: fresh `deploy`, 30 computes (forks 20)',
 'sc-reconf-nova-30': 'Scale: `-t nova reconfigure`, no change, 30 computes (forks 20)',
 'sc-reconf-nova-30-computeconf': 'Scale: `-t nova reconfigure` after nova-compute override, 30 computes (forks 20)',
 'sc-reconf-nova-30-forks5': 'Scale: `-t nova reconfigure`, no change, 30 computes, forks 5',
 'sc-reconf-nova-30-forks50': 'Scale: `-t nova reconfigure`, no change, 30 computes, forks 50',
 'sc-reconf-nova-30-limit1': 'Scale: `-t nova reconfigure --limit compute001`, no change, 30 computes',
}
def load(run):
    d = ROOT + run
    tr = [json.loads(l) for l in open(d + '/trace.jsonl')]
    ev = [json.loads(l) for l in open(d + '/events.jsonl')] if os.path.exists(d + '/events.jsonl') else []
    rj = json.load(open(d + '/result.json'))
    return tr, ev, rj
rows = []
out = ['# Lab results (generated by `harness/results_md.py`)', '',
       'All runs execute the **unmodified** `ussuri-eol` `site.yml` with Ansible 2.9.27 against simulated hosts '
       '(see [README](README.md) for the method and its limits). "Restarted/recreated" = handler actions recorded by the '
       '`kolla_docker` stub, which mirrors the real decision logic. Wall time is lab time (local connection, 4 vCPU), '
       'not a production estimate.', '']
for run in sorted(os.listdir(ROOT), key=lambda r: (r[0] != 't', r)):
    if not os.path.exists(ROOT + run + '/result.json'):
        continue
    tr, ev, rj = load(run)
    res = [t for t in tr if t['kind'] == 'result']
    hosts = sorted({r['host'] for r in res if r['host'] != 'localhost'})
    st = collections.Counter(r['status'] for r in res)
    acts = collections.defaultdict(lambda: collections.defaultdict(set))
    for e in ev:
        if e['module'] == 'kolla_docker' and e['action'] in ('RESTART', 'RECREATE', 'create+start', 'STOP'):
            acts[e['action']][e['name']].add(e['host'])
    oneshot = collections.Counter(e['name'] for e in ev if e['module'] == 'kolla_docker' and e['action'] == 'run-oneshot')
    pulls = sum(1 for e in ev if e['action'] == 'pull_image' and e.get('changed'))
    setups = sum(1 for e in ev if e['module'] == 'setup')
    comp = [h for h in hosts if h.startswith('compute')]
    per_comp = collections.Counter(r['host'] for r in res if r['host'] in comp)
    pc = '%d–%d' % (min(per_comp.values()), max(per_comp.values())) if per_comp else '-'
    def fmt(a):
        return '; '.join('%s×%d' % (n, len(h)) for n, h in sorted(acts[a].items())) or '–'
    out.append('## `%s`' % run)
    out.append('')
    out.append('*%s*' % DESC.get(run, run))
    out.append('')
    out.append('| Metric | Value |')
    out.append('|---|---|')
    out.append('| rc / lab wall time | %s / %.0f s |' % (rj['rc'], rj['seconds']))
    out.append('| hosts touched (excl. localhost) | %d |' % len(hosts))
    out.append('| task results ok / skipped / failed | %d / %d / %d |' % (st['ok'], st['skipped'], st['failed']))
    out.append('| task results per compute host | %s |' % pc)
    out.append('| `setup` (fact) module executions | %d |' % setups)
    out.append('| images actually downloaded | %d |' % pulls)
    out.append('| containers RESTARTED (name×hosts) | %s |' % fmt('RESTART'))
    out.append('| containers RECREATED | %s |' % fmt('RECREATE'))
    out.append('| containers created | %s |' % fmt('create+start'))
    out.append('| one-shot containers (name×runs) | %s |' % ('; '.join('%s×%d' % kv for kv in sorted(oneshot.items())) or '–'))
    out.append('')
open(OUT, 'w').write('\n'.join(out) + '\n')
print('wrote', OUT)
