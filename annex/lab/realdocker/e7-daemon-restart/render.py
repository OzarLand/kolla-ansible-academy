#!/usr/bin/env python3
"""e7: render the Kolla-Ansible (ussuri-eol) inputs the lab containers and the second dockerd use.

Usage: render.py <kolla-ansible src> <workdir>
Writes into <workdir>:
  etc-kolla/<svc>/config.json   from the real roles/*/templates/<svc>.json.j2 (jinja2)
  etc-kolla/<svc>/<project>.conf  placeholder (the stand-ins do not read it; kolla_set_configs needs the source)
  params.sh                     bash arrays VOL_<svc>=(-v ...) from the real roles/*/defaults/main.yml volume lists
  daemon-kolla.json             /etc/docker/daemon.json as roles/baremetal/tasks/post-install.yml:58-145 builds it
  daemon-kolla-live.json        the same with docker_custom_config: {"live-restore": true}
Lab substitutions (printed to stdout): node_config_directory -> <workdir>/etc-kolla; volume kolla_logs -> e7-kolla_logs.
"""
import json
import os
import sys

import jinja2
import yaml

src, work = sys.argv[1], sys.argv[2]
roles = os.path.join(src, 'ansible', 'roles')
etc = os.path.join(work, 'etc-kolla')

# group_vars/all.yml:7,16 and the facts of an Ubuntu host
VARS = {
    'container_config_directory': '/var/lib/kolla/config_files',
    'node_config_directory': etc,
    'ansible_facts': {'os_family': 'Debian'},
    'nova_dev_mode': False, 'heat_dev_mode': False,
    'kolla_dev_repos_directory': '/opt/stack/', 'distro_python_version': '3.6',
}
env = jinja2.Environment(undefined=jinja2.Undefined, keep_trailing_newline=True)
env.filters['bool'] = lambda v: v if isinstance(v, bool) else str(v).lower() in ('yes', 'true', '1', 'on')  # Ansible's

# (service dir, template, defaults file, volume list variable, project)
SERVICES = [
    ('nova-scheduler', 'nova/templates/nova-scheduler.json.j2', 'nova/defaults/main.yml',
     'nova_scheduler_default_volumes', 'nova'),
    ('nova-api-bootstrap', 'nova/templates/nova-api-bootstrap.json.j2', 'nova/defaults/main.yml',
     'nova_api_bootstrap_default_volumes', 'nova'),
    ('heat-engine', 'heat/templates/heat-engine.json.j2', 'heat/defaults/main.yml',
     'heat_engine_default_volumes', 'heat'),
]

params = ['# generated by render.py from %s (do not edit)' % os.path.abspath(src)]
for svc, tmpl, defaults, volvar, project in SERVICES:
    d = os.path.join(etc, svc)
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(roles, tmpl)) as f:
        rendered = env.from_string(f.read()).render(**VARS)
    json.loads(rendered)  # must be valid JSON, as kolla_set_configs requires
    with open(os.path.join(d, 'config.json'), 'w') as f:
        f.write(rendered)
    conf = os.path.join(d, project + '.conf')
    with open(conf, 'w') as f:
        f.write('[DEFAULT]\n# e7 lab placeholder, not a real %s.conf\n' % project)
    with open(os.path.join(roles, defaults)) as f:
        vols = yaml.safe_load(f)[volvar]
    # handlers pass volumes|reject('equalto', '') and kolla_docker generate_volumes() skips empty entries
    vols = [v for v in (env.from_string(x).render(**VARS) for x in vols) if v]
    vols = ['e7-' + v if v.startswith('kolla_logs:') else v for v in vols]
    params.append('VOL_%s=(%s)' % (svc.replace('-', '_'), ' '.join("-v '%s'" % v for v in vols)))
    print('%-20s config.json command=%-16s volumes=%s' % (svc, json.loads(rendered)['command'], vols))

with open(os.path.join(work, 'params.sh'), 'w') as f:
    f.write('\n'.join(params) + '\n')


def daemon_json(custom):
    """roles/baremetal/vars/main.yml:2-5 + post-install.yml combine steps, with the three
    docker_disable_* switches set to yes (Kolla's documented way to get bridge none / no iptables)."""
    gv = {'docker_log_max_file': '5', 'docker_log_max_size': '50m',            # group_vars/all.yml:130-131
          'docker_registry_insecure': False, 'docker_storage_driver': '', 'docker_runtime_directory': '',
          'docker_disable_default_iptables_rules': True, 'docker_disable_default_network': True,
          'docker_disable_ip_forward': True}
    cfg = {'log-opts': {'max-file': gv['docker_log_max_file'], 'max-size': gv['docker_log_max_size']}}
    if gv['docker_disable_default_iptables_rules']:
        cfg['iptables'] = False                                                # post-install.yml:102-105
    if gv['docker_disable_default_network']:
        cfg['bridge'] = 'none'                                                 # :116-119
    if gv['docker_disable_ip_forward']:
        cfg['ip-forward'] = False                                              # :130-133
    cfg.update(custom)                                                         # :135-137 docker_custom_config
    # to_nice_json (Ansible 2.9 plugins/filter/core.py): indent=4, sort_keys=True, separators=(',', ': ')
    return json.dumps(cfg, indent=4, sort_keys=True, separators=(',', ': '))


for name, custom in (('daemon-kolla.json', {}), ('daemon-kolla-live.json', {'live-restore': True})):
    with open(os.path.join(work, name), 'w') as f:
        f.write(daemon_json(custom))
    print('%s: %s' % (name, json.dumps(json.loads(daemon_json(custom)), sort_keys=True)))
